; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    clr a
    clr 0x10
    clr 0x1020
    clr (x)
    clr (#0x10,x)
    clr (#0x1020,x)
    clr (y)
    clr (#0x10,y)
    clr (#0x1020,y)
    clr (#0x10,sp)
    clr [0x10]
    clr [0x1020]

; CHECK: clr a           ; encoding: [0x4f]
; CHECK: clr 0x10        ; encoding: [0x72,0x5f,0x00,0x10]
; CHECK: clr 0x1020      ; encoding: [0x72,0x5f,0x10,0x20]
; CHECK: clr (x)         ; encoding: [0x7f]
; CHECK: clr (#0x10,x)   ; encoding: [0x72,0x4f,0x00,0x10]
; CHECK: clr (#0x1020,x) ; encoding: [0x72,0x4f,0x10,0x20]
; CHECK: clr (y)         ; encoding: [0x90,0x7f]
; CHECK: clr (#0x10,y)   ; encoding: [0x90,0x4f,0x00,0x10]
; CHECK: clr (#0x1020,y) ; encoding: [0x90,0x4f,0x10,0x20]
; CHECK: clr (#0x10,sp)  ; encoding: [0x0f,0x10]
; CHECK: clr [0x10]      ; encoding: [0x72,0x3f,0x00,0x10]
; CHECK: clr [0x1020]    ; encoding: [0x72,0x3f,0x10,0x20]

    clrw x
    clrw y

; CHECK: clrw x          ; encoding: [0x5f]
; CHECK: clrw y          ; encoding: [0x90,0x5f]
