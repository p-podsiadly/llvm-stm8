; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    rrc a
    rrc 0x10
    rrc 0x1020
    rrc (x)
    rrc (#0x10,x)
    rrc (#0x1020,x)
    rrc (y)
    rrc (#0x10,y)
    rrc (#0x1020,y)
    rrc (#0x10,sp)
    rrc [0x10]
    rrc [0x1020]

; CHECK: rrc a           ; encoding: [0x46]
; CHECK: rrc 0x10        ; encoding: [0x72,0x56,0x00,0x10]
; CHECK: rrc 0x1020      ; encoding: [0x72,0x56,0x10,0x20]
; CHECK: rrc (x)         ; encoding: [0x76]
; CHECK: rrc (#0x10,x)   ; encoding: [0x72,0x46,0x00,0x10]
; CHECK: rrc (#0x1020,x) ; encoding: [0x72,0x46,0x10,0x20]
; CHECK: rrc (y)         ; encoding: [0x90,0x76]
; CHECK: rrc (#0x10,y)   ; encoding: [0x90,0x46,0x00,0x10]
; CHECK: rrc (#0x1020,y) ; encoding: [0x90,0x46,0x10,0x20]
; CHECK: rrc (#0x10,sp)  ; encoding: [0x06,0x10]
; CHECK: rrc [0x10]      ; encoding: [0x72,0x36,0x00,0x10]
; CHECK: rrc [0x1020]    ; encoding: [0x72,0x36,0x10,0x20]

    rrcw x
    rrcw y

; CHECK: rrcw x          ; encoding: [0x56]
; CHECK: rrcw y          ; encoding: [0x90,0x56]
