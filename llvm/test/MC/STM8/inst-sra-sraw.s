; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    sra a
    sra 0x15
    sra 0x1505
    sra (x)
    sra (#0x15,x)
    sra (#0x1505,x)
    sra (y)
    sra (#0x15,y)
    sra (#0x1505,y)
    sra (#0x15,sp)
    sra [0x15]
    sra [0x1505]

; CHECK: sra a           ; encoding: [0x47]
; CHECK: sra 0x15        ; encoding: [0x72,0x57,0x00,0x15]
; CHECK: sra 0x1505      ; encoding: [0x72,0x57,0x15,0x05]
; CHECK: sra (x)         ; encoding: [0x77]
; CHECK: sra (#0x15,x)   ; encoding: [0x72,0x47,0x00,0x15]
; CHECK: sra (#0x1505,x) ; encoding: [0x72,0x47,0x15,0x05]
; CHECK: sra (y)         ; encoding: [0x90,0x77]
; CHECK: sra (#0x15,y)   ; encoding: [0x90,0x47,0x00,0x15]
; CHECK: sra (#0x1505,y) ; encoding: [0x90,0x47,0x15,0x05]
; CHECK: sra (#0x15,sp)  ; encoding: [0x07,0x15]
; CHECK: sra [0x15]      ; encoding: [0x72,0x37,0x00,0x15]
; CHECK: sra [0x1505]    ; encoding: [0x72,0x37,0x15,0x05]

    sraw x
    sraw y

; CHECK: sraw x         ; encoding: [0x57]
; CHECK: sraw y         ; encoding: [0x90,0x57]
