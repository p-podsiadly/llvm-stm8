; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    tnz a
    tnz 0x12
    tnz 0x1234
    tnz (x)
    tnz (#0x12,x)
    tnz (#0x1234,x)
    tnz (y)
    tnz (#0x12,y)
    tnz (#0x1234,y)
    tnz (#0x12,sp)
    tnz [0x12]
    tnz [0x1234]

; CHECK: tnz a           ; encoding: [0x4d]
; CHECK: tnz 0x12        ; encoding: [0x72,0x5d,0x00,0x12]
; CHECK: tnz 0x1234      ; encoding: [0x72,0x5d,0x12,0x34]
; CHECK: tnz (x)         ; encoding: [0x7d]
; CHECK: tnz (#0x12,x)   ; encoding: [0x72,0x4d,0x00,0x12]
; CHECK: tnz (#0x1234,x) ; encoding: [0x72,0x4d,0x12,0x34]
; CHECK: tnz (y)         ; encoding: [0x90,0x7d]
; CHECK: tnz (#0x12,y)   ; encoding: [0x90,0x4d,0x00,0x12]
; CHECK: tnz (#0x1234,y) ; encoding: [0x90,0x4d,0x12,0x34]
; CHECK: tnz (#0x12,sp)  ; encoding: [0x0d,0x12]
; CHECK: tnz [0x12]      ; encoding: [0x72,0x3d,0x00,0x12]
; CHECK: tnz [0x1234]    ; encoding: [0x72,0x3d,0x12,0x34]

    tnzw x
    tnzw y

; CHECK: tnzw x          ; encoding: [0x5d]
; CHECK: tnzw y          ; encoding: [0x90,0x5d]
