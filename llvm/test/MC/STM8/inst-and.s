; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    and a, #0x10
    and a, 0x10
    and a, 0x1020
    and a, (x)
    and a, (#0x10,x)
    and a, (#0x1020,x)
    and a, (y)
    and a, (#0x10,y)
    and a, (#0x1020,y)
    and a, (#0x10,sp)
    and a, [0x10]
    and a, [0x1020]

