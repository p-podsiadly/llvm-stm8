; CHECK: and a,(x)          ; encoding: [0xf4]
; CHECK: and a,(#0x10,x)    ; encoding: [0xd4,0x00,0x10]
; CHECK: and a,(#0x1020,x)  ; encoding: [0xd4,0x10,0x20]
; CHECK: and a,(y)          ; encoding: [0x90,0xf4]
