; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    sub a,  #0x10
    sub a,  0x10
    sub a,  0x1020
    sub a,  (x)
    sub a,  (#0x10,x)
    sub a,  (#0x1020,x)
    sub a,  (y)
    sub a,  (#0x10,y)
    sub a,  (#0x1020,y)
    sub a,  (#0x22,sp)
    sub a,  [0x10]
    sub a,  [0x1020]
    sub sp, #0x12

; CHECK: sub a,#0x10        ; encoding: [0xa0,0x10]
; CHECK: sub a,0x10         ; encoding: [0xc0,0x00,0x10]
; CHECK: sub a,0x1020       ; encoding: [0xc0,0x10,0x20]
; CHECK: sub a,(x)          ; encoding: [0xf0]
; CHECK: sub a,(#0x10,x)    ; encoding: [0xd0,0x00,0x10]
; CHECK: sub a,(#0x1020,x)  ; encoding: [0xd0,0x10,0x20]
; CHECK: sub a,(y)          ; encoding: [0x90,0xf0]
; CHECK: sub a,(#0x10,y)    ; encoding: [0x90,0xd0,0x00,0x10]
; CHECK: sub a,(#0x1020,y)  ; encoding: [0x90,0xd0,0x10,0x20]
; CHECK: sub a,(#0x22,sp)   ; encoding: [0x10,0x22]
; CHECK: sub a,[0x10]       ; encoding: [0x72,0xc0,0x00,0x10]
; CHECK: sub a,[0x1020]     ; encoding: [0x72,0xc0,0x10,0x20]
; CHECK: sub sp,#0x12       ; encoding: [0x52,0x12]
