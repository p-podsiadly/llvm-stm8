; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    dec a
    dec 0x10
    dec 0x1020
    dec (x)
    dec (#0x10,x)
    dec (#0x1020,x)
    dec (y)
    dec (#0x10,y)
    dec (#0x1020,y)
    dec (#0x10,sp)
    dec [0x10]
    dec [0x1020]

; CHECK: dec a           ; encoding: [0x4a]
; CHECK: dec 0x10        ; encoding: [0x72,0x5a,0x00,0x10]
; CHECK: dec 0x1020      ; encoding: [0x72,0x5a,0x10,0x20]
; CHECK: dec (x)         ; encoding: [0x7a]
; CHECK: dec (#0x10,x)   ; encoding: [0x72,0x4a,0x00,0x10]
; CHECK: dec (#0x1020,x) ; encoding: [0x72,0x4a,0x10,0x20]
; CHECK: dec (y)         ; encoding: [0x90,0x7a]
; CHECK: dec (#0x10,y)   ; encoding: [0x90,0x4a,0x00,0x10]
; CHECK: dec (#0x1020,y) ; encoding: [0x90,0x4a,0x10,0x20]
; CHECK: dec [0x10]      ; encoding: [0x72,0x3a,0x00,0x10]
; CHECK: dec [0x1020]    ; encoding: [0x72,0x3a,0x10,0x20]

    decw x
    decw y

; CHECK: decw x          ; encoding: [0x5a]
; CHECK: decw y          ; encoding: [0x90,0x5a]
