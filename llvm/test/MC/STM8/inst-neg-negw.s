; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    neg a
    neg 0x10
    neg 0x1020
    neg (x)
    neg (#0x10,x)
    neg (#0x1020,x)
    neg (y)
    neg (#0x10,y)
    neg (#0x1020,y)
    neg (#0x10,sp)
    neg [0x10]
    neg [0x1020]

; CHECK: neg a           ; encoding: [0x40]
; CHECK: neg 0x10        ; encoding: [0x72,0x50,0x00,0x10]
; CHECK: neg 0x1020      ; encoding: [0x72,0x50,0x10,0x20]
; CHECK: neg (x)         ; encoding: [0x70]
; CHECK: neg (#0x10,x)   ; encoding: [0x72,0x40,0x00,0x10]
; CHECK: neg (#0x1020,x) ; encoding: [0x72,0x40,0x10,0x20]
; CHECK: neg (y)         ; encoding: [0x90,0x70]
; CHECK: neg (#0x10,y)   ; encoding: [0x90,0x40,0x00,0x10]
; CHECK: neg (#0x1020,y) ; encoding: [0x90,0x40,0x10,0x20]
; CHECK: neg (#0x10,sp)  ; encoding: [0x00,0x10]
; CHECK: neg [0x10]      ; encoding: [0x72,0x30,0x00,0x10]
; CHECK: neg [0x1020]    ; encoding: [0x72,0x30,0x10,0x20]

    negw x
    negw y

; CHECK: negw x          ; encoding: [0x50]
; CHECK: negw y          ; encoding: [0x90,0x50]
