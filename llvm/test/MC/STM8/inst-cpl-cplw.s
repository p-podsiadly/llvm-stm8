; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    cpl a
    cpl 0x10
    cpl 0x1020
    cpl (x)
    cpl (#0x10,x)
    cpl (#0x1020,x)
    cpl (y)
    cpl (#0x10,y)
    cpl (#0x1020,y)
    cpl (#0x10,sp)
    cpl [0x10]
    cpl [0x1020]

; CHECK: cpl a           ; encoding: [0x43]
; CHECK: cpl 0x10        ; encoding: [0x72,0x53,0x00,0x10]
; CHECK: cpl 0x1020      ; encoding: [0x72,0x53,0x10,0x20]
; CHECK: cpl (x)         ; encoding: [0x73]
; CHECK: cpl (#0x10,x)   ; encoding: [0x72,0x43,0x00,0x10]
; CHECK: cpl (#0x1020,x) ; encoding: [0x72,0x43,0x10,0x20]
; CHECK: cpl (y)         ; encoding: [0x90,0x73]
; CHECK: cpl (#0x10,y)   ; encoding: [0x90,0x43,0x00,0x10]
; CHECK: cpl (#0x1020,y) ; encoding: [0x90,0x43,0x10,0x20]
; CHECK: cpl (#0x10,sp)  ; encoding: [0x03,0x10]
; CHECK: cpl [0x10]      ; encoding: [0x72,0x33,0x00,0x10]
; CHECK: cpl [0x1020]    ; encoding: [0x72,0x33,0x10,0x20]

    cplw x
    cplw y

; CHECK: cplw x          ; encoding: [0x53]
; CHECK: cplw y          ; encoding: [0x90,0x53]
