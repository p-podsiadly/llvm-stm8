; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:
    addw x,  #0x1000
    addw x,  0x1000
    addw x,  (#0x10,sp)
    addw y,  #0x1000
    addw y,  0x1000
    addw y,  (#0x10,sp)
    addw sp, #0x10

; CHECK: addw   x,#0x1000    ; encoding: [0x1c,0x10,0x00]
; CHECK: addw   x,0x1000     ; encoding: [0x72,0xbb,0x10,0x00]
; CHECK: addw   x,(#0x10,sp) ; encoding: [0x72,0xfb,0x10]
; CHECK: addw   y,#0x1000    ; encoding: [0x72,0xa9,0x10,0x00]
; CHECK: addw   y,0x1000     ; encoding: [0x72,0xb9,0x10,0x00]
; CHECK: addw   y,(#0x10,sp) ; encoding: [0x72,0xf9,0x10]
; CHECK: addw   sp,#0x10     ; encoding: [0x5b,0x10]
