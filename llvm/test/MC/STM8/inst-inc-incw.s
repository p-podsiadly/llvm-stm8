; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    inc a
    inc 0x10
    inc 0x1020
    inc (x)
    inc (#0x10,x)
    inc (#0x1020,x)
    inc (y)
    inc (#0x10,y)
    inc (#0x1020,y)
    inc (#0x10,sp)
    inc [0x10]
    inc [0x1020]

; CHECK: inc a           ; encoding: [0x4c]
; CHECK: inc 0x10        ; encoding: [0x72,0x5c,0x00,0x10]
; CHECK: inc 0x1020      ; encoding: [0x72,0x5c,0x10,0x20]
; CHECK: inc (x)         ; encoding: [0x7c]
; CHECK: inc (#0x10,x)   ; encoding: [0x72,0x4c,0x00,0x10]
; CHECK: inc (#0x1020,x) ; encoding: [0x72,0x4c,0x10,0x20]
; CHECK: inc (y)         ; encoding: [0x90,0x7c]
; CHECK: inc (#0x10,y)   ; encoding: [0x90,0x4c,0x00,0x10]
; CHECK: inc (#0x1020,y) ; encoding: [0x90,0x4c,0x10,0x20]
; CHECK: inc (#0x10,sp)  ; encoding: [0x0c,0x10]
; CHECK: inc [0x10]      ; encoding: [0x72,0x3c,0x00,0x10]
; CHECK: inc [0x1020]    ; encoding: [0x72,0x3c,0x10,0x20]

    incw x
    incw y

; CHECK: incw x          ; encoding: [0x5c]
; CHECK: incw y          ; encoding: [0x90,0x5c]
