; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    rlc a
    rlc 0x10
    rlc 0x1020
    rlc (x)
    rlc (#0x10,x)
    rlc (#0x1020,x)
    rlc (y)
    rlc (#0x10,y)
    rlc (#0x1020,y)
    rlc (#0x10,sp)
    rlc [0x10]
    rlc [0x1020]

; CHECK: rlc a           ; encoding: [0x49]
; CHECK: rlc 0x10        ; encoding: [0x72,0x59,0x00,0x10]
; CHECK: rlc 0x1020      ; encoding: [0x72,0x59,0x10,0x20]
; CHECK: rlc (x)         ; encoding: [0x79]
; CHECK: rlc (#0x10,x)   ; encoding: [0x72,0x49,0x00,0x10]
; CHECK: rlc (#0x1020,x) ; encoding: [0x72,0x49,0x10,0x20]
; CHECK: rlc (y)         ; encoding: [0x90,0x79]
; CHECK: rlc (#0x10,y)   ; encoding: [0x90,0x49,0x00,0x10]
; CHECK: rlc (#0x1020,y) ; encoding: [0x90,0x49,0x10,0x20]
; CHECK: rlc (#0x10,sp)  ; encoding: [0x09,0x10]
; CHECK: rlc [0x10]      ; encoding: [0x72,0x39,0x00,0x10]
; CHECK: rlc [0x1020]    ; encoding: [0x72,0x39,0x10,0x20]

    rlcw x
    rlcw y

; CHECK: rlcw x      ; encoding: [0x59]
; CHECK: rlcw y      ; encoding: [0x90,0x59]
