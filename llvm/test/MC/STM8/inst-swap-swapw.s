; RUN: llvm-mc -triple stm8 -show-encoding < %s | FileCheck %s

test:

    swap a
    swap 0x12
    swap 0x1234
    swap (x)
    swap (#0x12,x)
    swap (#0x1234,x)
    swap (y)
    swap (#0x12,y)
    swap (#0x1234,y)
    swap (#0x12,sp)
    swap [0x12]
    swap [0x1234]

; CHECK: swap a             ; encoding: [0x4e]
; CHECK: swap 0x12          ; encoding: [0x72,0x5e,0x00,0x12]
; CHECK: swap 0x1234        ; encoding: [0x72,0x5e,0x12,0x34]
; CHECK: swap (x)           ; encoding: [0x7e]
; CHECK: swap (#0x12,x)     ; encoding: [0x72,0x4e,0x00,0x12]
; CHECK: swap (#0x1234,x)   ; encoding: [0x72,0x4e,0x12,0x34]
; CHECK: swap (y)           ; encoding: [0x90,0x7e]
; CHECK: swap (#0x12,y)     ; encoding: [0x90,0x4e,0x00,0x12]
; CHECK: swap (#0x1234,y)   ; encoding: [0x90,0x4e,0x12,0x34]
; CHECK: swap (#0x12,sp)    ; encoding: [0x0e,0x12]
; CHECK: swap [0x12]        ; encoding: [0x72,0x3e,0x00,0x12]
; CHECK: swap [0x1234]      ; encoding: [0x72,0x3e,0x12,0x34]

    swapw x
    swapw y

; CHECK: swapw x            ; encoding: [0x5e]
; CHECK: swapw y            ; encoding: [0x90,0x5e]
